/**
 * Source of `volt-computer`, the macOS helper behind the computer_* tools: Accessibility (AX) reads
 * and actions on other apps, and CGEvent mouse/keyboard input. Volt compiles it with `swiftc` on
 * first use into its user data folder (keyed by a hash of this text), so macOS attributes the
 * Accessibility permission to Volt. One JSON command in argv[1], one JSON object on stdout.
 */
export const COMPUTER_HELPER_SWIFT = [
	'// volt-computer: Volt\'s desktop computer-use helper (macOS). One JSON command in argv[1], one JSON object out.',
	'// Commands: status {request?}, apps {}, tree {pid, maxDepth?, maxNodes?}, act {pid, id, action, value?}, input {actions[], pid?}',
	'import AppKit',
	'import ApplicationServices',
	'import CoreGraphics',
	'import Foundation',
	'',
	'func emit(_ value: Any) {',
	'	let data = (try? JSONSerialization.data(withJSONObject: value, options: [])) ?? Data("{\\"error\\":\\"encode\\"}".utf8)',
	'	FileHandle.standardOutput.write(data)',
	'	exit(0)',
	'}',
	'func fail(_ message: String) -> Never { emit(["error": message]); exit(1) }',
	'',
	'guard CommandLine.arguments.count > 1, let raw = CommandLine.arguments[1].data(using: .utf8),',
	'	let cmd = (try? JSONSerialization.jsonObject(with: raw)) as? [String: Any], let op = cmd["op"] as? String else {',
	'	fail("usage: volt-computer \'{\\"op\\":\\"status\\"}\'")',
	'}',
	'',
	'func attr(_ el: AXUIElement, _ name: String) -> AnyObject? {',
	'	var value: AnyObject?',
	'	return AXUIElementCopyAttributeValue(el, name as CFString, &value) == .success ? value : nil',
	'}',
	'func str(_ el: AXUIElement, _ name: String) -> String? {',
	'	if let s = attr(el, name) as? String, !s.isEmpty { return s }',
	'	if let n = attr(el, name) as? NSNumber { return n.stringValue }',
	'	return nil',
	'}',
	'func frame(_ el: AXUIElement) -> [String: Int]? {',
	'	guard let p = attr(el, kAXPositionAttribute), let s = attr(el, kAXSizeAttribute) else { return nil }',
	'	var point = CGPoint.zero, size = CGSize.zero',
	'	AXValueGetValue(p as! AXValue, .cgPoint, &point)',
	'	AXValueGetValue(s as! AXValue, .cgSize, &size)',
	'	return ["x": Int(point.x), "y": Int(point.y), "w": Int(size.width), "h": Int(size.height)]',
	'}',
	'func actions(_ el: AXUIElement) -> [String] {',
	'	var names: CFArray?',
	'	guard AXUIElementCopyActionNames(el, &names) == .success, let list = names as? [String] else { return [] }',
	'	return list.map { $0.replacingOccurrences(of: "AX", with: "").lowercased() }',
	'}',
	'func children(_ el: AXUIElement) -> [AXUIElement] { (attr(el, kAXChildrenAttribute) as? [AXUIElement]) ?? [] }',
	'',
	'func appRoot(_ pid: pid_t) -> AXUIElement { AXUIElementCreateApplication(pid) }',
	'func topWindow(_ pid: pid_t) -> AXUIElement? {',
	'	let app = appRoot(pid)',
	'	if let w = attr(app, kAXFocusedWindowAttribute) { return (w as! AXUIElement) }',
	'	return (attr(app, kAXWindowsAttribute) as? [AXUIElement])?.first',
	'}',
	'/// Elements are named by their child-index path from the window ("w" = the window, "w.0.3" = …), "m.…" for the menu bar.',
	'func resolve(_ pid: pid_t, _ id: String) -> AXUIElement? {',
	'	var parts = id.split(separator: ".").map(String.init)',
	'	guard let head = parts.first else { return nil }',
	'	parts.removeFirst()',
	'	var el: AXUIElement',
	'	if head == "w" { guard let w = topWindow(pid) else { return nil }; el = w }',
	'	else if head == "m" { guard let m = attr(appRoot(pid), kAXMenuBarAttribute) else { return nil }; el = m as! AXUIElement }',
	'	else { return nil }',
	'	for p in parts {',
	'		guard let i = Int(p) else { return nil }',
	'		let kids = children(el)',
	'		guard i >= 0, i < kids.count else { return nil }',
	'		el = kids[i]',
	'	}',
	'	return el',
	'}',
	'',
	'switch op {',
	'case "status":',
	'	if (cmd["request"] as? Bool) == true {',
	'		let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary',
	'		_ = AXIsProcessTrustedWithOptions(options)',
	'		_ = CGRequestScreenCaptureAccess()',
	'	}',
	'	let front = NSWorkspace.shared.frontmostApplication',
	'	let screen = NSScreen.main?.frame ?? .zero',
	'	emit(["accessibility": AXIsProcessTrusted(), "screenRecording": CGPreflightScreenCaptureAccess(),',
	'		"frontmost": front?.localizedName ?? "", "frontmostPid": Int(front?.processIdentifier ?? 0),',
	'		"screen": ["w": Int(screen.width), "h": Int(screen.height)]])',
	'',
	'case "apps":',
	'	let apps = NSWorkspace.shared.runningApplications.filter { $0.activationPolicy == .regular }.map { app -> [String: Any] in',
	'		["name": app.localizedName ?? "", "bundleId": app.bundleIdentifier ?? "", "pid": Int(app.processIdentifier), "active": app.isActive, "hidden": app.isHidden]',
	'	}',
	'	emit(["apps": apps])',
	'',
	'case "tree":',
	'	guard AXIsProcessTrusted() else { fail("accessibility") }',
	'	guard let pid = (cmd["pid"] as? NSNumber)?.int32Value else { fail("tree needs pid") }',
	'	let maxDepth = (cmd["maxDepth"] as? Int) ?? 12',
	'	let maxNodes = (cmd["maxNodes"] as? Int) ?? 400',
	'	var nodes: [[String: Any]] = []',
	'	var truncated = false',
	'	func walk(_ el: AXUIElement, _ id: String, _ depth: Int) {',
	'		if nodes.count >= maxNodes { truncated = true; return }',
	'		let role = (str(el, kAXRoleAttribute) ?? "").replacingOccurrences(of: "AX", with: "")',
	'		let name = str(el, kAXTitleAttribute) ?? str(el, kAXDescriptionAttribute) ?? str(el, kAXLabelValueAttribute) ?? ""',
	'		let value = role == "SecureTextField" ? (str(el, kAXValueAttribute) != nil ? "••••" : nil) : str(el, kAXValueAttribute)',
	'		let acts = actions(el).filter { $0 != "showalternateui" && $0 != "showdefaultui" && $0 != "scrolltovisible" }',
	'		let enabled = (attr(el, kAXEnabledAttribute) as? Bool) ?? true',
	'		let focused = (attr(el, kAXFocusedAttribute) as? Bool) ?? false',
	'		// Skip anonymous layout groups but keep walking through them.',
	'		let interesting = !name.isEmpty || value != nil || !acts.isEmpty || depth == 0 || ["StaticText", "TextField", "TextArea", "Image", "Table", "List", "Outline"].contains(role)',
	'		if interesting {',
	'			var node: [String: Any] = ["id": id, "role": role, "depth": depth]',
	'			if !name.isEmpty { node["name"] = String(name.prefix(120)) }',
	'			if let v = value { node["value"] = String(v.prefix(200)) }',
	'			if !acts.isEmpty { node["actions"] = acts }',
	'			if !enabled { node["disabled"] = true }',
	'			if focused { node["focused"] = true }',
	'			if let f = frame(el) { node["frame"] = f }',
	'			nodes.append(node)',
	'		}',
	'		if depth >= maxDepth { return }',
	'		for (i, child) in children(el).enumerated() { walk(child, "\\(id).\\(i)", interesting ? depth + 1 : depth) }',
	'	}',
	'	guard let window = topWindow(pid) else { fail("no window") }',
	'	walk(window, "w", 0)',
	'	emit(["title": str(window, kAXTitleAttribute) ?? "", "nodes": nodes, "truncated": truncated])',
	'',
	'case "act":',
	'	guard AXIsProcessTrusted() else { fail("accessibility") }',
	'	guard let pid = (cmd["pid"] as? NSNumber)?.int32Value, let id = cmd["id"] as? String, let action = cmd["action"] as? String else { fail("act needs pid, id, action") }',
	'	guard let el = resolve(pid, id) else { fail("stale") }',
	'	var result: AXError = .success',
	'	switch action {',
	'	case "set_value":',
	'		result = AXUIElementSetAttributeValue(el, kAXValueAttribute as CFString, ((cmd["value"] as? String) ?? "") as CFString)',
	'	case "focus":',
	'		result = AXUIElementSetAttributeValue(el, kAXFocusedAttribute as CFString, kCFBooleanTrue)',
	'	default:',
	'		let name = "AX" + action.prefix(1).uppercased() + action.dropFirst().replacingOccurrences(of: "_", with: "")',
	'		result = AXUIElementPerformAction(el, (["Press": "AXPress", "Showmenu": "AXShowMenu", "Raise": "AXRaise", "Confirm": "AXConfirm", "Cancel": "AXCancel", "Increment": "AXIncrement", "Decrement": "AXDecrement", "Pick": "AXPick"][String(name.dropFirst(2))] ?? name) as CFString)',
	'	}',
	'	emit(["ok": result == .success, "code": Int(result.rawValue)])',
	'',
	'case "input":',
	'	guard AXIsProcessTrusted() else { fail("accessibility") }',
	'	if let pid = (cmd["pid"] as? NSNumber)?.int32Value, let app = NSRunningApplication(processIdentifier: pid) {',
	'		app.activate()',
	'		usleep(250_000)',
	'	}',
	'	let src = CGEventSource(stateID: .hidSystemState)',
	'	let keyCodes: [String: CGKeyCode] = ["return": 36, "enter": 36, "tab": 48, "space": 49, "delete": 51, "backspace": 51, "escape": 53, "esc": 53, "left": 123, "right": 124, "down": 125, "up": 126, "home": 115, "end": 119, "pageup": 116, "pagedown": 121, "forwarddelete": 117,',
	'		"a": 0, "s": 1, "d": 2, "f": 3, "h": 4, "g": 5, "z": 6, "x": 7, "c": 8, "v": 9, "b": 11, "q": 12, "w": 13, "e": 14, "r": 15, "y": 16, "t": 17, "1": 18, "2": 19, "3": 20, "4": 21, "6": 22, "5": 23, "=": 24, "9": 25, "7": 26, "-": 27, "8": 28, "0": 29, "]": 30, "o": 31, "u": 32, "[": 33, "i": 34, "p": 35, "l": 37, "j": 38, "\'": 39, "k": 40, ";": 41, "\\\\": 42, ",": 43, "/": 44, "n": 45, "m": 46, ".": 47, "`": 50,',
	'		"f1": 122, "f2": 120, "f3": 99, "f4": 118, "f5": 96, "f6": 97, "f7": 98, "f8": 100, "f9": 101, "f10": 109, "f11": 103, "f12": 111]',
	'	func point(_ v: Any?) -> CGPoint? { guard let d = v as? [String: Any], let x = (d["x"] as? NSNumber)?.doubleValue, let y = (d["y"] as? NSNumber)?.doubleValue else { return nil }; return CGPoint(x: x, y: y) }',
	'	func mouse(_ type: CGEventType, _ at: CGPoint, _ button: CGMouseButton, _ clicks: Int = 1) {',
	'		let e = CGEvent(mouseEventSource: src, mouseType: type, mouseCursorPosition: at, mouseButton: button)',
	'		e?.setIntegerValueField(.mouseEventClickState, value: Int64(clicks))',
	'		e?.post(tap: .cghidEventTap)',
	'	}',
	'	var done = 0',
	'	for case let step as [String: Any] in (cmd["actions"] as? [Any]) ?? [] {',
	'		if let at = point(step["click"]) {',
	'			let d = step["click"] as! [String: Any]',
	'			let right = (d["button"] as? String) == "right"',
	'			let count = max(1, min(3, (d["count"] as? Int) ?? 1))',
	'			mouse(.mouseMoved, at, .left)',
	'			for i in 1...count {',
	'				mouse(right ? .rightMouseDown : .leftMouseDown, at, right ? .right : .left, i)',
	'				mouse(right ? .rightMouseUp : .leftMouseUp, at, right ? .right : .left, i)',
	'			}',
	'		} else if let at = point(step["move"]) {',
	'			mouse(.mouseMoved, at, .left)',
	'		} else if let d = step["drag"] as? [String: Any], let from = point(d["from"]), let to = point(d["to"]) {',
	'			mouse(.leftMouseDown, from, .left)',
	'			for i in 1...12 { let t = Double(i) / 12; mouse(.leftMouseDragged, CGPoint(x: from.x + (to.x - from.x) * t, y: from.y + (to.y - from.y) * t), .left); usleep(12_000) }',
	'			mouse(.leftMouseUp, to, .left)',
	'		} else if let text = step["type"] as? String {',
	'			for scalar in text.utf16 {',
	'				var c = scalar',
	'				let down = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: true); down?.keyboardSetUnicodeString(stringLength: 1, unicodeString: &c); down?.post(tap: .cghidEventTap)',
	'				let up = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: false); up?.keyboardSetUnicodeString(stringLength: 1, unicodeString: &c); up?.post(tap: .cghidEventTap)',
	'				usleep(4_000)',
	'			}',
	'		} else if let combo = step["key"] as? String {',
	'			var parts = combo.lowercased().split(separator: "+").map(String.init)',
	'			guard let key = parts.popLast(), let code = keyCodes[key] else { fail("unknown key \\(combo)") }',
	'			var flags: CGEventFlags = []',
	'			for m in parts { switch m { case "cmd", "command", "meta": flags.insert(.maskCommand); case "shift": flags.insert(.maskShift); case "alt", "option", "opt": flags.insert(.maskAlternate); case "ctrl", "control": flags.insert(.maskControl); case "fn": flags.insert(.maskSecondaryFn); default: fail("unknown modifier \\(m)") } }',
	'			let down = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: true); down?.flags = flags; down?.post(tap: .cghidEventTap)',
	'			let up = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: false); up?.flags = flags; up?.post(tap: .cghidEventTap)',
	'		} else if let d = step["scroll"] as? [String: Any] {',
	'			if let at = point(d) { mouse(.mouseMoved, at, .left) }',
	'			let dy = Int32((d["dy"] as? NSNumber)?.intValue ?? 0), dx = Int32((d["dx"] as? NSNumber)?.intValue ?? 0)',
	'			CGEvent(scrollWheelEvent2Source: src, units: .pixel, wheelCount: 2, wheel1: -dy, wheel2: -dx, wheel3: 0)?.post(tap: .cghidEventTap)',
	'		} else if let ms = step["wait"] as? NSNumber {',
	'			usleep(useconds_t(min(10_000, max(0, ms.intValue)) * 1000))',
	'		} else {',
	'			fail("step \\(done + 1): unknown action")',
	'		}',
	'		done += 1',
	'		usleep(60_000)',
	'	}',
	'	let loc = CGEvent(source: nil)?.location ?? .zero',
	'	emit(["ok": true, "done": done, "cursor": ["x": Int(loc.x), "y": Int(loc.y)], "frontmost": NSWorkspace.shared.frontmostApplication?.localizedName ?? ""])',
	'',
	'default:',
	'	fail("unknown op \\(op)")',
	'}',
].join('\n');
