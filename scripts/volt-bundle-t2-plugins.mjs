// Bundles Volt's first-party T2 plugins (spec H.5): one file each, no imports, no node_modules,
// evaluated in the plugin host's Compartment. Deterministic (fixed options, no timestamps, no
// source paths), so the committed bundle is checked like the generated manifests:
// `voltMemoryPlugin.test.ts` fails when it is out of date.
//
//   src/vs/workbench/services/voltRuntime/common/memory/memoryPlugin.ts -> extensions/volt-memory/plugin/memory.js
//
// Usage: node scripts/volt-bundle-t2-plugins.mjs [--check]

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { createRequire } from 'module';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const esbuild = createRequire(join(root, 'build', 'package.json'))('esbuild');

export const T2_PLUGINS = [
	{ entry: 'src/vs/workbench/services/voltRuntime/common/memory/memoryPlugin.ts', out: 'extensions/volt-memory/plugin/memory.js' },
];

const HEADER = `/*---------------------------------------------------------------------------------------------
 *  Copyright (c) Volt ADK. All rights reserved.
 *  Licensed under the MIT License. See License.txt in the project root for license information.
 *--------------------------------------------------------------------------------------------*/

// Generated by scripts/volt-bundle-t2-plugins.mjs. Do not edit: change the source and run it.
`;

/** The bundle's text for one plugin. */
export async function bundle(plugin) {
	const result = await esbuild.build({
		entryPoints: [join(root, plugin.entry)],
		bundle: true,
		write: false,
		format: 'cjs',
		platform: 'neutral',
		target: 'es2022',
		charset: 'ascii',
		legalComments: 'none',
		treeShaking: true,
		// The service decorator in voltMemory.ts is not part of the plugin.
		pure: ['createDecorator'],
		sourcemap: false,
		logLevel: 'silent',
	});
	const code = result.outputFiles[0].text
		// No build machine paths in the bundle.
		.replace(/^\/\/ (?:src|out)\/.*\n/gm, '');
	return HEADER + code;
}

async function main() {
	const check = process.argv.includes('--check');
	let stale = 0;
	for (const plugin of T2_PLUGINS) {
		const text = await bundle(plugin);
		const file = join(root, plugin.out);
		if (check) {
			let current = '';
			try {
				current = readFileSync(file, 'utf8');
			} catch {
				// Missing counts as stale.
			}
			if (current !== text) {
				stale++;
				console.error(`${plugin.out} is out of date: run node scripts/volt-bundle-t2-plugins.mjs`);
			}
		} else {
			mkdirSync(dirname(file), { recursive: true });
			writeFileSync(file, text);
			console.log(`wrote ${plugin.out} (${text.length} bytes)`);
		}
	}
	process.exit(stale ? 1 : 0);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	await main();
}
