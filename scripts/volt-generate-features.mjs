// Writes Volt's feature catalog data from the built-in feature manifests:
//   extensions/volt-*/package.json  ->  src/vs/workbench/contrib/voltCustomize/common/voltFeatureManifests.generated.ts
//                                   ->  src/vs/workbench/services/voltPlugins/common/voltBuiltinAgents.generated.ts
// `voltFeatures.ts` builds `VOLT_FEATURES` from the first (falling back to its hand-written list if
// the data is invalid); `voltAgentDefinitions.ts` builds the agent CLIs Volt runs from the second
// (`contributes.voltAgents`, spec H.12 / M2). `voltFeatureExtensions.test.ts` fails when either
// generated file is out of date.
//
// Usage: node scripts/volt-generate-features.mjs [--check]

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src/vs/workbench/contrib/voltCustomize/common/voltFeatureManifests.generated.ts');
const agentsTarget = join(root, 'src/vs/workbench/services/voltPlugins/common/voltBuiltinAgents.generated.ts');

/** Keep in sync with `VOLT_CONTRIBUTION_POINTS` (voltContributions.ts); the test compares them. */
const POINTS = ['voltTools', 'voltSlotItems', 'voltSettingsPages', 'voltSurfaces', 'voltDock', 'voltAgents', 'voltCapabilities', 'voltModule'];

function manifests() {
	const folders = readdirSync(join(root, 'extensions')).filter(name => name.startsWith('volt-')).sort();
	const out = [];
	for (const folder of folders) {
		const file = join(root, 'extensions', folder, 'package.json');
		if (!existsSync(file)) {
			continue;
		}
		const pkg = JSON.parse(readFileSync(file, 'utf8'));
		const contributes = {};
		for (const point of POINTS) {
			if (pkg.contributes?.[point] !== undefined) {
				contributes[point] = pkg.contributes[point];
			}
		}
		out.push({ publisher: pkg.publisher, name: pkg.name, ...(pkg.engines?.volt ? { engines: { volt: pkg.engines.volt } } : {}), contributes });
	}
	return out;
}

/** A TS literal in the repo's style: single quotes, tabs, identifier keys unquoted. */
function literal(value, indent) {
	const pad = '\t'.repeat(indent + 1);
	const close = '\t'.repeat(indent);
	if (Array.isArray(value)) {
		if (!value.length) {
			return '[]';
		}
		if (value.every(item => typeof item !== 'object' || item === null)) {
			return `[${value.map(item => literal(item, indent)).join(', ')}]`;
		}
		return `[\n${value.map(item => `${pad}${literal(item, indent + 1)},`).join('\n')}\n${close}]`;
	}
	if (value && typeof value === 'object') {
		const entries = Object.entries(value);
		if (!entries.length) {
			return '{}';
		}
		return `{\n${entries.map(([key, item]) => `${pad}${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : quote(key)}: ${literal(item, indent + 1)},`).join('\n')}\n${close}}`;
	}
	return typeof value === 'string' ? quote(value) : JSON.stringify(value);
}

function quote(text) {
	return `'${text.replace(/\\/g, '\\\\').replace(/'/g, '\\\'').replace(/\n/g, '\\n')}'`;
}

const HEADER = `/*---------------------------------------------------------------------------------------------
 *  Copyright (c) Volt ADK. All rights reserved.
 *  Licensed under the MIT License. See License.txt in the project root for license information.
 *--------------------------------------------------------------------------------------------*/

// Generated by scripts/volt-generate-features.mjs from extensions/volt-*/package.json. Do not edit:
// change the manifest and run \`node scripts/volt-generate-features.mjs\`.
`;

const all = manifests();

const source = `${HEADER}
import type { IVoltPluginManifest } from '../../../services/voltPlugins/common/voltContributions.js';

export const VOLT_FEATURE_MANIFESTS: readonly IVoltPluginManifest[] = ${literal(all, 0)};
`;

/** The built-ins' agents only: services read them, and services may not import contrib code. */
const agents = all.filter(manifest => manifest.contributes.voltAgents).map(manifest => ({ extensionId: `${manifest.publisher}.${manifest.name}`, agents: manifest.contributes.voltAgents }));

const agentsSource = `${HEADER}
import type { IVoltAgentContribution } from './voltContributions.js';

export const VOLT_BUILTIN_AGENTS: readonly { readonly extensionId: string; readonly agents: readonly IVoltAgentContribution[] }[] = ${literal(agents, 0)};
`;

const outputs = [[target, source], [agentsTarget, agentsSource]];

if (process.argv.includes('--check')) {
	let stale = false;
	for (const [file, text] of outputs) {
		const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
		if (current !== text) {
			console.error(`${file} is out of date: run node scripts/volt-generate-features.mjs`);
			stale = true;
		}
	}
	if (stale) {
		process.exit(1);
	}
} else {
	for (const [file, text] of outputs) {
		writeFileSync(file, text);
		console.log(`wrote ${file}`);
	}
}
