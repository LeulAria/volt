// Captures the theme CSS a running Volt window generates (color variables, codicon glyphs, token
// colors, file icons) into the web app's sources, so the web app looks exactly like the window.
// Run against a Volt window started with --remote-debugging-port, in the agent layout:
//   node build/volt/captureDesktopTheme.mjs <cdpPort>

import { createRequire } from 'node:module';
import * as fs from 'node:fs';
import * as path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const require = createRequire(path.join(root, 'package.json'));
const CDP = require('chrome-remote-interface');
const port = Number(process.argv[2]);
if (!port) {
	console.error('usage: node build/volt/captureDesktopTheme.mjs <cdpPort>');
	process.exit(1);
}

const targets = await CDP.List({ port });
const page = targets.find(t => t.type === 'page' && t.url.includes('workbench'));
const client = await CDP({ port, target: page });
const { result } = await client.Runtime.evaluate({
	returnByValue: true,
	expression: `(() => {
		const sections = [];
		for (const sheet of document.styleSheets) {
			if (sheet.href) { continue; }
			let rules;
			try { rules = sheet.cssRules; } catch { continue; }
			const owner = sheet.ownerNode;
			sections.push({ name: owner.className || owner.id || 'style', text: [...rules].map(r => r.cssText).join('\\n') });
		}
		return sections;
	})()`,
});
await client.close();

const header = (what) => `/*---------------------------------------------------------------------------------------------
 *  Copyright (c) Volt ADK. All rights reserved.
 *  Licensed under the MIT License. See License.txt in the project root for license information.
 *--------------------------------------------------------------------------------------------*/

/*
 * Generated by build/volt/captureDesktopTheme.mjs: ${what}, captured from a Volt agent window so
 * the web app matches it. Do not edit by hand.
 */
`;

const theme = [];
let icons = '';
for (const section of result.value) {
	const first = section.text.split('\n')[0] ?? '';
	if (section.name === 'contributedFileIconTheme') {
		icons = section.text.replace(/url\("vscode-file:\/\/vscode-app[^"]*\/([^/"]+)"\)/g, 'url("/fileicons/$1")');
	} else if (['contributedColorTheme', 'codiconStyles', 'vscode-tokens-styles'].includes(section.name) || first.startsWith(':root { --z-index') || first.startsWith('.monaco-workbench { --vscode-sash')) {
		theme.push(`/* ${section.name} */\n` + section.text.split('\n').filter(line => !line.startsWith('@font-face') && !line.includes('vscode-file://')).join('\n'));
	}
}
const media = path.join(root, 'src/vs/workbench/contrib/voltAgentWeb/browser/media');
fs.writeFileSync(path.join(media, 'desktopTheme.css'), header('the theme CSS for Cursor Dark (color variables, codicon glyphs, token colors)') + theme.join('\n') + '\n');
fs.writeFileSync(path.join(media, 'desktopFileIcons.css'), header('the file icon theme CSS, icon URLs pointing at /fileicons/') + icons + '\n');
console.log(`wrote desktopTheme.css (${theme.length} sections) and desktopFileIcons.css (${icons.length} bytes)`);
