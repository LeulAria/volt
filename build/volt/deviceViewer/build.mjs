// Bundles src/index.ts with three.js into one ES module for the workbench (loaded on demand).
// Run `npm install && npm run build` here after changing src/; commit the output.
import { build } from '../../node_modules/esbuild/lib/main.js';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../../src/vs/workbench/contrib/voltAgent/browser/devices/vendor/voltDeviceViewer.js');
await build({
	entryPoints: [join(here, 'src/index.ts')],
	outfile: out,
	bundle: true,
	format: 'esm',
	platform: 'browser',
	target: 'es2022',
	minify: true,
	legalComments: 'none',
	banner: { js: '// Generated by build/volt/deviceViewer (npm run build). Do not edit. Includes three.js (MIT), Effect (MIT) and code from T3 Code (MIT).' },
	logLevel: 'info',
});
