// Bundles build/volt/mobileCore.ts (the agent server client, remote services and home model from
// src/vs, no DOM) into apps/mobile/src/core/voltCore.js for the React Native app, with its
// declarations in apps/mobile/src/core/types.
//   node build/volt/buildMobileCore.mjs [--watch]

import { createRequire } from 'node:module';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { execFileSync } from 'node:child_process';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');
const root = path.dirname(path.dirname(path.dirname(new URL(import.meta.url).pathname)));
const outfile = path.join(root, 'apps', 'mobile', 'src', 'core', 'voltCore.js');

/** @type {import('esbuild').BuildOptions} */
const options = {
	entryPoints: [path.join(root, 'build', 'volt', 'mobileCore.ts')],
	outfile,
	bundle: true,
	format: 'esm',
	platform: 'neutral',
	target: 'es2020',
	logLevel: 'warning',
	legalComments: 'none',
	banner: { js: '// Generated by build/volt/buildMobileCore.mjs from src/vs. Do not edit.\n/* eslint-disable */' },
	tsconfigRaw: { compilerOptions: { experimentalDecorators: true, useDefineForClassFields: false } },
	plugins: [{
		name: 'ts-from-js',
		setup(build) {
			// Sources import each other as .js; esbuild must find the .ts next to them.
			build.onResolve({ filter: /\.js$/ }, args => {
				if (!args.path.startsWith('.')) {
					return undefined;
				}
				const ts = path.join(args.resolveDir, args.path.replace(/\.js$/, '.ts'));
				return fs.existsSync(ts) ? { path: ts } : undefined;
			});
		},
	}],
};

fs.mkdirSync(path.dirname(outfile), { recursive: true });
if (process.argv.includes('--watch')) {
	const ctx = await esbuild.context(options);
	await ctx.watch();
	console.log(`[mobile core] watching -> ${path.relative(root, outfile)}`);
} else {
	await esbuild.build(options);
	// Declarations, so the app type-checks against the sources without compiling them.
	fs.rmSync(path.join(path.dirname(outfile), 'types'), { recursive: true, force: true });
	execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', path.join(root, 'build', 'volt', 'tsconfig.mobileCore.json')], { stdio: 'inherit' });
	console.log(`[mobile core] ${path.relative(root, outfile)} (${Math.round(fs.statSync(outfile).size / 1024)} KB)`);
}
