// Bundles src/index.ts with three.js into one ES module for the workbench (loaded on demand).
// Run `npm install && npm run build` here after changing src/; commit the output.
// To render devices outside Volt, see harness/README.md.
import { build } from '../../node_modules/esbuild/lib/main.js';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const vendor = join(here, '../../../src/vs/workbench/contrib/voltAgent/browser/preview/deviceStudio/vendor');

const common = {
	bundle: true,
	format: 'esm',
	platform: 'browser',
	target: 'es2022',
	legalComments: 'none',
	logLevel: 'info',
};

await build({
	...common,
	entryPoints: [join(here, 'src/index.ts')],
	outfile: join(vendor, 'voltDeviceStudio.js'),
	minify: true,
	banner: { js: '// Generated by build/volt/deviceStudio (npm run build). Do not edit. Includes three.js (MIT).' },
});
