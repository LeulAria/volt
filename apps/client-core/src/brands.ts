/** Provider ids that share a mark (the desktop's providerFamily.ts). */
const BRAND_FAMILIES: Readonly<Record<string, string>> = {
	codex: 'codex',
	openai: 'codex',
	claude: 'claude',
	'claude-code': 'claude',
	anthropic: 'claude',
	cursor: 'cursor',
	'cursor-acp': 'cursor',
	grok: 'grok',
	xai: 'grok',
	opencode: 'opencode',
	pi: 'pi',
	antigravity: 'antigravity',
	agy: 'antigravity',
	gemini: 'antigravity',
	'gemini-cli': 'antigravity',
	'gemini-acp': 'antigravity',
	kimi: 'kimi',
	muse: 'muse',
	fx: 'fx',
	ollama: 'local',
	lmstudio: 'local',
	'openai-compat': 'local',
	openrouter: 'openrouter',
};

/** A provider's (harness's) mark: Codex, Claude, Antigravity... */
export function providerBrand(providerId: string | undefined): IBrand {
	const id = (providerId ?? '').toLowerCase();
	const family = BRAND_FAMILIES[id] ?? Object.keys(BRAND_FAMILIES).find(key => id.startsWith(key)) ?? id;
	return BRANDS[BRAND_FAMILIES[family] ?? family] ?? BRANDS.generic;
}

/**
 * A model's own mark: its maker's, read from the name (Claude Sonnet on Antigravity shows
 * Claude's), else its provider's.
 */
export function modelBrand(label: string | undefined, providerId: string | undefined): IBrand {
	const name = (label ?? '').toLowerCase();
	if (/claude|opus|sonnet|haiku|fable/.test(name)) {
		return BRANDS.claude;
	}
	if (/gemini/.test(name)) {
		return BRANDS.gemini;
	}
	if (/grok/.test(name)) {
		return BRANDS.grok;
	}
	if (/kimi/.test(name)) {
		return BRANDS.kimi;
	}
	if (/muse/.test(name)) {
		return BRANDS.muse;
	}
	const provider = providerBrand(providerId);
	if (/\bgpt|codex|\bo[34]\b/.test(name) && provider.id !== 'codex') {
		return BRANDS.openai;
	}
	return provider;
}
