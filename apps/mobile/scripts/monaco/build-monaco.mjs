// Builds the phone's Monaco and writes src/files/monacoBundle.ts: the editor script, its
// stylesheet and Geist Mono, which the editor page inlines, so opening a file needs no network.
//
//   cd scripts/monaco && npm install && npm run build
//
// Vite and monaco-editor come from this folder's package.json.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, '../..');
execFileSync(path.join(here, 'node_modules/.bin/vite'), ['build', '--config', path.join(here, 'vite.config.mjs')], { cwd: here, stdio: 'inherit' });

const js = readFileSync(path.join(here, 'dist/monaco.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
const css = readFileSync(path.join(here, 'dist/monaco.css'), 'utf8').replace(/<\/style/gi, '<\\/style');
const font = readFileSync(path.join(mobile, 'assets/fonts/GeistMono-Variable.ttf')).toString('base64');
const out = path.join(mobile, 'src/files/monacoBundle.ts');
writeFileSync(out, [
	'/*---------------------------------------------------------------------------------------------',
	' *  Copyright (c) Volt ADK. All rights reserved.',
	' *  Licensed under the MIT License. See License.txt in the project root for license information.',
	' *--------------------------------------------------------------------------------------------*/',
	'',
	'// Generated by scripts/monaco/build-monaco.mjs (Monaco is MIT, Geist Mono is OFL). Do not edit.',
	'',
	`export const MONACO_JS = ${JSON.stringify(js)};`,
	`export const MONACO_CSS = ${JSON.stringify(css)};`,
	`export const GEIST_MONO_TTF_BASE64 = ${JSON.stringify(font)};`,
	'',
].join('\n'));
console.log(`${path.relative(mobile, out)}: ${(js.length / 1e6).toFixed(2)} MB script, ${(css.length / 1e3).toFixed(0)} KB css, ${(font.length / 1e3).toFixed(0)} KB font`);
