// Builds the phone's diff and file viewer and writes src/files/diffsBundle.ts: @pierre/diffs
// with Highlights (its WebAssembly inlined), which the viewer page injects, so opening a diff
// needs no network. Geist Mono comes from monacoBundle.ts.
//
//   cd scripts/diffs && npm install && npm run build
//
// Vite and @pierre/diffs come from this folder's package.json.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, '../..');
execFileSync(path.join(here, 'node_modules/.bin/vite'), ['build', '--config', path.join(here, 'vite.config.mjs')], { cwd: here, stdio: 'inherit' });

const js = readFileSync(path.join(here, 'dist/diffs.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
const out = path.join(mobile, 'src/files/diffsBundle.ts');
writeFileSync(out, [
	'/*---------------------------------------------------------------------------------------------',
	' *  Copyright (c) Volt ADK. All rights reserved.',
	' *  Licensed under the MIT License. See License.txt in the project root for license information.',
	' *--------------------------------------------------------------------------------------------*/',
	'',
	'// Generated by scripts/diffs/build-diffs.mjs (@pierre/diffs and @pierre/highlights are Apache-2.0). Do not edit.',
	'',
	`export const DIFFS_JS = ${JSON.stringify(js)};`,
	'',
].join('\n'));
console.log(`${path.relative(mobile, out)}: ${(js.length / 1e6).toFixed(2)} MB script`);
