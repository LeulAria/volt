#!/usr/bin/env python3
"""Writes src/files/materialIcons.ts: the desktop's file icons (Material Icon Theme) for the files
people open most, so the phone's file rows look like Volt's.

    python3 scripts/gen-file-icons.py [path/to/PKief.material-icon-theme]

Defaults to the theme the desktop build downloads into .build/builtInExtensions.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
THEME = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '.build', 'builtInExtensions', 'PKief.material-icon-theme')
OUT = os.path.join(HERE, '..', 'src', 'files', 'materialIcons.ts')

EXTENSIONS = '''
ts tsx mts cts d.ts js jsx mjs cjs json jsonc json5 md mdx markdown txt log css scss sass less html htm vue svelte astro
py pyi ipynb go rs swift kt kts java c h cpp cc hpp cs rb php sh bash zsh fish ps1 bat yml yaml toml ini xml plist
sql graphql gql proto dart lua r scala ex exs erl hs ml clj elm zig nim
png jpg jpeg gif webp ico bmp svg mp4 mov mp3 wav pdf zip gz tar lock env diff patch
test.ts test.tsx spec.ts spec.tsx test.js spec.js stories.tsx d.mts module.css
'''.split()

FILE_NAMES = '''
package.json package-lock.json yarn.lock pnpm-lock.yaml bun.lockb tsconfig.json jsconfig.json readme.md license license.md
changelog.md contributing.md .gitignore .gitattributes .gitmodules .npmrc .nvmrc .editorconfig .prettierrc .eslintrc
.eslintrc.js eslint.config.js eslint.config.mjs dockerfile docker-compose.yml compose.yaml makefile cargo.toml go.mod go.sum
.env .env.local vite.config.ts vite.config.js next.config.js next.config.mjs tailwind.config.js tailwind.config.ts
babel.config.js metro.config.js app.json podfile gemfile requirements.txt pyproject.toml claude.md agents.md
'''.split()


def main() -> None:
	manifest = json.load(open(os.path.join(THEME, 'dist', 'material-icons.json')))
	defs = manifest['iconDefinitions']
	ext_map = {e: manifest['fileExtensions'][e] for e in EXTENSIONS if e in manifest['fileExtensions']}
	name_map = {n: manifest['fileNames'][n] for n in FILE_NAMES if n in manifest['fileNames']}
	lang_map = {k: v for k, v in manifest['languageIds'].items()}
	# Language ids whose icon we already carry for an extension, so a path the maps miss still lands well.
	icons = set(ext_map.values()) | set(name_map.values()) | {'file', 'folder', 'folder-open'}
	lang_map = {k: v for k, v in lang_map.items() if v in icons}

	svgs = {}
	for name in sorted(icons):
		path = os.path.normpath(os.path.join(THEME, 'dist', defs[name]['iconPath']))
		svg = open(path).read().strip()
		svg = re.sub(r'\s*xml:space="preserve"', '', svg)
		svg = re.sub(r'>\s+<', '><', svg)
		svgs[name] = svg

	lines = [
		'/*---------------------------------------------------------------------------------------------',
		' *  Copyright (c) Volt ADK. All rights reserved.',
		' *  Licensed under the MIT License. See License.txt in the project root for license information.',
		' *--------------------------------------------------------------------------------------------*/',
		'',
		'// Generated by scripts/gen-file-icons.py from the Material Icon Theme (MIT), the desktop\'s file icons. Do not edit.',
		'',
		'export const MATERIAL_SVGS: Readonly<Record<string, string>> = {',
	]
	for name, svg in svgs.items():
		lines.append(f'\t{json.dumps(name)}: {json.dumps(svg)},')
	lines.append('};')
	lines.append('')
	for const, data in (('MATERIAL_EXTENSIONS', ext_map), ('MATERIAL_FILE_NAMES', name_map), ('MATERIAL_LANGUAGES', lang_map)):
		lines.append(f'export const {const}: Readonly<Record<string, string>> = {{')
		for key, value in sorted(data.items()):
			lines.append(f'\t{json.dumps(key)}: {json.dumps(value)},')
		lines.append('};')
		lines.append('')
	open(OUT, 'w').write('\n'.join(lines))
	print(f'{len(svgs)} icons, {len(ext_map)} extensions, {len(name_map)} names -> {os.path.relpath(OUT)} ({os.path.getsize(OUT) // 1024} KB)')


main()
